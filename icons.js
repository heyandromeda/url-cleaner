export function createIcon(name, { size = 16, className = "icon" } = {}) {
  const paths = ICONS[name];
  if (!paths) throw new Error(`Unknown icon: ${name}`);

  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("width", String(size));
  svg.setAttribute("height", String(size));
  svg.setAttribute("aria-hidden", "true");
  svg.setAttribute("focusable", "false");
  for (const token of className.split(/\s+/).filter(Boolean)) {
    svg.classList.add(token);
  }
  if (size === 18) svg.classList.add("icon-18");
  if (size === 16) svg.classList.add("icon-16");

  for (const pathData of paths) {
    const path = document.createElementNS("http://www.w3.org/2000/svg", "path");
    path.setAttribute("d", pathData);
    path.setAttribute("fill", "none");
    path.setAttribute("stroke", "currentColor");
    path.setAttribute("stroke-width", String(STROKE));
    path.setAttribute("stroke-linecap", "round");
    path.setAttribute("stroke-linejoin", "round");
    svg.append(path);
  }

  return svg;
}

export function wrapIconButton(button, iconName, labelText) {
  button.replaceChildren();
  const wrap = document.createElement("span");
  wrap.className = "icon-button";
  wrap.append(createIcon(iconName, { size: 16 }), document.createTextNode(labelText));
  button.append(wrap);
}
